def _default(field: Any) -> str:
    if field.default is PydanticUndefined and field.default_factory is None:
        return "**required**"
    value = field.default_factory() if field.default_factory is not None else field.default
    if isinstance(value, SecretStr):
        return "(secret)"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value) or "(empty)"
    if value is None:
        return "(unset)"
    return str(getattr(value, "value", value))


def _type_hint(annotation: Any) -> str:
    args = [a for a in typing.get_args(annotation) if a is not type(None)]
    if typing.get_origin(annotation) is typing.Literal:
        return " / ".join(f"`{a}`" for a in typing.get_args(annotation))
    if isinstance(annotation, type) and issubclass(annotation, enum.Enum):
        return " / ".join(f"`{m.value}`" for m in annotation)
    if annotation is SecretStr or SecretStr in args:
        return "secret"
    if typing.get_origin(annotation) is list or any(typing.get_origin(a) is list for a in args):
        return "comma-separated list"
    for arg in args:
        hint = _type_hint(arg)
        if hint:
            return hint
    return ""


def _bounds(metadata: list[Any]) -> list[str]:
    parts: list[str] = []
    for meta in metadata:
        if isinstance(meta, annotated_types.Ge):
            parts.append(f">= {meta.ge}")
        elif isinstance(meta, annotated_types.Gt):
            parts.append(f"> {meta.gt}")
        elif isinstance(meta, annotated_types.Le):
            parts.append(f"<= {meta.le}")
        elif isinstance(meta, annotated_types.Lt):
            parts.append(f"< {meta.lt}")
        elif isinstance(meta, annotated_types.MinLen):
            parts.append(f"min length {meta.min_length}")
        elif isinstance(meta, annotated_types.MaxLen):
            parts.append(f"max length {meta.max_length}")
        elif isinstance(meta, StringConstraints):
            if meta.min_length is not None:
                parts.append(f"min length {meta.min_length}")
            if meta.max_length is not None:
                parts.append(f"max length {meta.max_length}")
            if meta.pattern is not None:
                parts.append(f"pattern `{meta.pattern}`")
        elif getattr(meta, "pattern", None):
            parts.append(f"pattern `{meta.pattern}`")
    return parts


def _matches(name: str, prefixes: tuple[str, ...]) -> bool:
    return any(name == p or name.startswith(p) for p in prefixes)


def render_configuration() -> str:
    fields = dict(Settings.model_fields)
    undocumented = [name for name, field in fields.items() if not field.description]
    if undocumented:
        msg = f"settings without a docstring: {undocumented}"
        raise SystemExit(msg)
    lines = [
        "# Configuration reference",
        "",
        GENERATED_NOTE,
        "",
        "Every setting is read from an environment variable named `AEGIS_<NAME>` (upper case), or from a",
        "`.env` file in development. Secrets are typed as `SecretStr`: they never appear in logs, `repr()` or",
        "validation errors. With `AEGIS_ENV=production` the process refuses to start with unsafe values",
        "(SQLite, no Redis, embedded vector index, wildcard hosts/CORS, development mailbox, no metrics",
        "token, HSTS off, DEBUG or non-JSON logging, optional staff two-factor authentication, the",
        "simulated payment provider, placeholder secrets).",
        "",
        "An empty variable (`AEGIS_METRICS_TOKEN=`) means *unset* - the default applies - so an empty value can",
        "never become a valid credential. In production, secrets can also be mounted as files: set",
        "`AEGIS_SECRETS_DIR` to a directory holding one file per variable (`AEGIS_JWT_SECRET`,",
        "`AEGIS_DATABASE_URL`, ...); environment variables take precedence over `.env`, which takes",
        "precedence over secret files.",
        "",
        "Additional variables read outside the settings model: `AEGIS_SECRETS_DIR` (see above),",
        "`AEGIS_MIGRATION_DATABASE_URL` (schema-owner connection used by migrations), `AEGIS_DB_APP_ROLE`",
        "(runtime role granted by migration 0002), `AEGIS_BOOTSTRAP_ADMIN_PASSWORD` (non-interactive",
        "`aegis create-admin`), `AEGIS_TEST_DATABASE_URL` (run the test suite on PostgreSQL). The Docker",
        "Compose file additionally reads `POSTGRES_PASSWORD`, `AEGIS_DB_OWNER_PASSWORD`,",
        "`AEGIS_DB_APP_PASSWORD`, `REDIS_PASSWORD` and `QDRANT_API_KEY` (created by `aegis init-env --docker`).",
        "",
    ]
    used: set[str] = set()
    for title, prefixes in CONFIG_GROUPS:
        names = [n for n in fields if n not in used and _matches(n, prefixes)]
        if not names:
            continue
        used.update(names)
        lines += [
            f"## {title}",
            "",
            "| Variable | Meaning | Default | Constraints |",
            "|---|---|---|---|",
        ]
        for name in names:
            field = fields[name]
            constraints = ", ".join(
                p for p in (_type_hint(field.annotation), *_bounds(field.metadata)) if p
            )
            lines.append(
                f"| `AEGIS_{name.upper()}` | {field.description} | {_default(field)} "
                f"| {constraints or '-'} |"
            )
        lines.append("")
    leftovers = [n for n in fields if n not in used]
    if leftovers:
        msg = f"settings not assigned to a documentation group: {leftovers}"
        raise SystemExit(msg)
    return "\n".join(lines).rstrip() + "\n"


