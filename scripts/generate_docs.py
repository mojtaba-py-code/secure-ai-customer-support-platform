def _nested_metadata(annotation: Any) -> list[Any]:
    """Constraints declared inside ``Annotated[...]``, also within ``X | None``."""
    if typing.get_origin(annotation) is typing.Annotated:
        return list(annotation.__metadata__)
    return [m for arg in typing.get_args(annotation) for m in _nested_metadata(arg)]


def _parameter_type(annotation: Any) -> str:
    args = typing.get_args(annotation)
    origin = typing.get_origin(annotation)
    if origin is typing.Annotated:
        return _parameter_type(args[0])
    if origin in (typing.Union, types.UnionType):
        text = " or ".join(_parameter_type(a) for a in args if a is not type(None))
        return f"{text} or null" if type(None) in args else text
    if origin is typing.Literal:
        return "one of " + ", ".join(f"`{a}`" for a in args)
    if isinstance(annotation, type) and issubclass(annotation, enum.Enum):
        return "one of " + ", ".join(f"`{m.value}`" for m in annotation)
    return _type_name(annotation).strip("`")


def _parameter_rows(model: type[Any]) -> list[str]:
    rows = []
    for name, field in model.model_fields.items():
        metadata = [*field.metadata, *_nested_metadata(field.annotation)]
        constraints = ", ".join(dict.fromkeys(_bounds(metadata))) or "-"
        rows.append(
            f"| `{name}` | {_parameter_type(field.annotation)} | {constraints} "
            f"| {field.description or '-'} |"
        )
    return rows


def render_tools() -> str:
    registry = IntentRegistry.load_default(known_tools=frozenset(t.name for t in TOOLS))
    allowed_by: dict[str, list[str]] = {}
    for intent in registry.all():
        for tool in intent.tools:
            allowed_by.setdefault(tool, []).append(intent.name)
    lines = [
        "# Tools and intents",
        "",
        GENERATED_NOTE,
        "",
        "The model never touches the database or the network directly. It can only *request* one of",
        "the tools below; the executor ([agent.md](agent.md#6-tool-execution)) then checks the intent's",
        "allow-list, the per-turn budgets, the argument schema and the caller's permission before the",
        "handler runs - and every handler goes through the same services (and ownership checks) as the",
        "REST API. Side effects: **read** (no change), **write** (low-risk, audited),",
        "**propose** (creates a pending action the customer must confirm through the API - the model",
        "can never complete a refund or cancellation on its own), **escalate** (hands over to a human).",
        "",
        "## Tools",
        "",
    ]
    for tool in TOOLS:
        intents = ", ".join(f"`{name}`" for name in allowed_by.get(tool.name, [])) or "-"
        lines += [
            f"### `{tool.name}`",
            "",
            tool.description,
            "",
            f"- Side effect: **{tool.side_effect.value}**",
            f"- Permission: `{tool.permission.value}`",
            f"- Calls per turn: at most {tool.max_calls_per_turn}",
            f"- Allowed for intents: {intents}",
            "",
            "| Parameter | Type | Constraints | Description |",
            "|---|---|---|---|",
            *_parameter_rows(tool.input_model),
            "",
        ]
    lines += [
        "## Intents",
        "",
        "Defined in `src/aegis/agents/intents.toml` and validated at start-up.",
        "",
        "| Intent | Description | Default priority | Knowledge searched | Always escalates |",
        "|---|---|---|---|---|",
    ]
    for intent in registry.all():
        knowledge = ", ".join(f"`{k.value}`" for k in intent.knowledge) or "-"
        lines.append(
            f"| `{intent.name}` | {intent.description} | {intent.default_priority.value} "
            f"| {knowledge} | {'yes' if intent.always_escalate else 'no'} |"
        )
    return "\n".join(lines).rstrip() + "\n"


# =================================================================================================
TARGETS: dict[str, Callable[[], str]] = {
    "configuration.md": render_configuration,
    "api-reference.md": render_api_reference,
    "tools.md": render_tools,
}


def render_all() -> dict[Path, str]:
    return {DOCS / name: render() for name, render in TARGETS.items()}


def main() -> int:
    documents = render_all()
    if "--check" in sys.argv:
        stale = [
            path.name
            for path, content in documents.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"out of date: {', '.join(stale)}; run python scripts/generate_docs.py")
            return 1
        return 0
    DOCS.mkdir(parents=True, exist_ok=True)
    for path, content in documents.items():
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote docs/{path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
