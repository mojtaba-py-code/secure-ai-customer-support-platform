_RATE_LIMIT_PATTERN = re.compile(r"rate_limits\.(\w+)")


def _walk(dependant: Dependant) -> Iterator[Dependant]:
    for child in dependant.dependencies:
        yield child
        yield from _walk(child)


def _type_name(annotation: Any) -> str:
    if annotation is None:
        return "-"
    if isinstance(annotation, type) and not typing.get_args(annotation):
        return f"`{annotation.__name__}`"
    # "aegis.schemas.common.Page[aegis.schemas.admin.UserOut]" -> "Page[UserOut]"
    text = re.sub(r"\b[\w.]+\.(\w+)", r"\1", repr(annotation).replace("typing.", ""))
    # A "|" must be escaped inside a table cell, even within a code span (GFM).
    return "`" + text.replace("|", "\\|") + "`"


def _is_ours(func: Callable[..., Any]) -> bool:
    return str(getattr(func, "__module__", "")).startswith("aegis.")


def _limits_in(func: Callable[..., Any]) -> list[str]:
    try:
        return _RATE_LIMIT_PATTERN.findall(inspect.getsource(func))
    except (OSError, TypeError):
        return []


def _route_facts(route: APIRoute, *, versioned: bool) -> dict[str, str]:
    dependants = list(_walk(route.dependant))
    calls = [d.call for d in dependants if d.call is not None]
    if versioned:
        calls += [d.dependency for d in V1_DEPENDENCIES if d.dependency is not None]
    requirements = [r for r in (deps.requirement_of(c) for c in calls) if r is not None]
    authenticated = deps.get_principal in calls
    if requirements:
        access = ", ".join(f"`{r.permission.value}`" for r in requirements)
    elif authenticated:
        access = "authenticated ¹"
    else:
        access = "public"

    limits: list[str] = ["api_ip"] if deps.ip_rate_limit in calls else []
    limits += _limits_in(route.endpoint)
    # Limits applied by the route's own helper dependencies (e.g. the MFA management budget).
    shared = {deps.get_principal, deps.ip_rate_limit}
    for call in calls:
        if call not in shared and deps.requirement_of(call) is None and _is_ours(call):
            limits += _limits_in(call)
    if authenticated:
        limits.append("api_user")
    if any(r.admin_rate_limit for r in requirements):
        limits.append("admin")

    headers = {param.alias for d in (route.dependant, *dependants) for param in d.header_params}
    body = route.dependant.body_params
    body_text = "-"
    if body:
        annotation = body[0].field_info.annotation
        body_text = _type_name(annotation)
        if "multipart" in repr(body[0].field_info).lower() or len(body) > 1:
            body_text = "multipart form"
    status = route.status_code or 200
    response = _type_name(route.response_model) if route.response_model else "-"
    notes = []
    if "Idempotency-Key" in headers:
        notes.append("`Idempotency-Key`")
    query = [p.alias for p in route.dependant.query_params]
    if query:
        notes.append("query: " + ", ".join(f"`{q}`" for q in query))
    return {
        "access": access,
        "limits": ", ".join(f"`{name}`" for name in dict.fromkeys(limits)) or "-",
        "body": body_text,
        "response": f"{status} {response}".strip(),
        "notes": "; ".join(notes) or "-",
    }


def _routes() -> list[tuple[str, APIRoute]]:
    """(full path, route) for every documented route, in registration order."""
    found = [*health_router.routes, *(route for router in V1_ROUTERS for route in router.routes)]
    return [
        (route.path, route)
        for route in found
        if isinstance(route, APIRoute) and route.include_in_schema
    ]


def render_api_reference() -> str:
    lines = [
        "# API reference",
        "",
        GENERATED_NOTE,
        "",
        "All endpoints live under `/api/v1` except the health probes. Conventions (authentication,",
        "errors, pagination, idempotency, rate limits) are described in [api.md](api.md); the full",
        "request and response schemas are served at `/docs` when the API documentation is enabled",
        "(`AEGIS_API_DOCS_ENABLED`, on by default outside production).",
        "",
        "**Access** lists the permission the route's dependencies enforce before the handler runs.",
        "¹ *authenticated*: any signed-in role may call the route; the service layer then decides",
        "per record (customers see only their own records - anything else is reported as *not found*;",
        "staff need the matching `*_any` permission). **Rate limits** are the policies the route",
        "applies (see `AEGIS_RL_*` in [configuration.md](configuration.md)); `/metrics` is described",
        "in [operations.md](operations.md).",
        "",
    ]
    by_tag: dict[str, list[tuple[str, APIRoute]]] = {}
    for path, route in _routes():
        tag = str(route.tags[0]) if route.tags else "other"
        by_tag.setdefault(tag, []).append((path, route))
    for tag, routes in by_tag.items():
        lines += [
            f"## {tag.capitalize()}",
            "",
            "| Method | Path | Access | Rate limits | Body | Response | Notes |",
            "|---|---|---|---|---|---|---|",
        ]
        for path, route in routes:
            facts = _route_facts(route, versioned=path.startswith(API_V1_PREFIX))
            for method in sorted(route.methods or ()):
                lines.append(
                    f"| {method} | `{path}` | {facts['access']} | {facts['limits']} "
                    f"| {facts['body']} | {facts['response']} | {facts['notes']} |"
                )
        lines.append("")

    roles = list(Role)
    lines += [
        "## Role permissions (RBAC matrix)",
        "",
        "| Permission | " + " | ".join(r.value for r in roles) + " |",
        "|---|" + "---|" * len(roles),
    ]
    for permission in Permission:
        marks = ["yes" if permission in ROLE_PERMISSIONS[r] else "" for r in roles]
        lines.append(f"| `{permission.value}` | " + " | ".join(marks) + " |")
    return "\n".join(lines).rstrip() + "\n"


