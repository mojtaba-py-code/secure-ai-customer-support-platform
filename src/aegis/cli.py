"""Command-line interface: ``aegis <command>``.

Commands
    serve               run the API (uvicorn, no server header, proxy headers off by default)
    worker              run the background worker (indexing + housekeeping)
    migrate             apply database migrations (alembic upgrade head)
    seed                load the fictional demo business (development only)
    index-kb            index pending knowledge-base documents once (--rebuild: into an empty collection)
    create-admin        create an administrator (password prompted, never echoed)
    generate-secrets    print fresh random secrets for the environment
    init-env            write a .env with fresh secrets: development (default) or --docker
    rotate-encryption   re-encrypt encrypted columns with the newest key
    check-config        validate the configuration and print a redacted summary
    healthcheck         container health probe for the API (or --worker)
"""

from __future__ import annotations

import argparse
import asyncio
import getpass
import os
import secrets
import sys
import time
from pathlib import Path
from typing import Any

from aegis.core.config import Settings, load_settings
